package com.notification.domain;

/**
 * 알림 한 건에 적용된 재시도/기한 정책의 버전.
 *
 * <p>정책은 운영 CRUD 테이블이 아니라 <b>코드의 불변 버전</b>으로 둔다. 한 번 등록된 알림은 끝까지
 * 등록 당시 버전으로 판정해야, 배포 중에 같은 알림의 실패 예산이나 기한이 바뀌지 않는다.
 */
public enum PolicyVersion {

    /**
     * P1 이전에 등록된 행. 재시도 2회(1분·5분) 고정이고 기한({@code expiresAt})이 없다.
     * 과거 {@code retryCount}로 실제 외부 호출 수를 역산하지 않으며, 기한을 소급 생성하지도 않는다.
     */
    LEGACY_V0,

    /**
     * P1의 타입별 정책. 타입마다 지연 목록과 기한이 다르고, Stuck 회수 횟수를 실패 예산과 분리한다.
     * 신규 EMAIL 행에만 활성화한다 — 구버전 worker가 선점할 수 있는 동안에는 켜지 않는다.
     */
    TYPE_V1
}
